export function formatManPage(entry: ManPageEntry): string {
  const header = `${entry.name.toUpperCase()}(${entry.section})                   Red Hat Enterprise Linux 9.3                   ${entry.name.toUpperCase()}(${entry.section})`;
  const lines = [
    header,
    '',
    'NAME',
    `       ${entry.name} - ${entry.summary}`,
    '',
    'SYNOPSIS',
    `       ${entry.synopsis}`,
    '',
    'DESCRIPTION',
    `       ${entry.description}`,
    '',
    'OPTIONS / PARAMETERS',
    ...entry.options.flatMap((o) => [`       ${o.flag}`, `              ${o.detail}`]),
    '',
    'EXAMPLES',
    ...entry.examples.map((ex) => `       $ ${ex}`),
    '',
    'SEE ALSO',
    `       ${entry.seeAlso.join(', ')}`,
  ];
  return lines.join('\n');
}
